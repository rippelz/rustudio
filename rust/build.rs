//! Generates two tables from the sources:
//! - plugin_claims.rs: the plugin API domain's member claims. The domain lives
//!   in studio (src/plugin_host, above the engine), so the engine's own
//!   member_claims.rs cannot include them; src/plugin_host/api.rs includes this
//!   file and passes the tables in its Domain at registration.
//! - engine_reads.rs: ENGINE_READS / ENGINE_FIRES for the gap telemetry. They
//!   are generated here, in the crate that sees every tree the engine code
//!   lives in, and the telemetry in rustudio-core receives them at start-up
//!   (`telemetry::install_engine_tables`): core must not watch sources above
//!   it, so a studio edit doesn't recompile it.
//!
//! The engine's member_claims.rs is generated by
//! crates/rustudio-engine/build.rs now. The source walk here and there is the
//! same file: crates/rustudio-engine/build/source_claims.rs.

include!(concat!(env!("CARGO_MANIFEST_DIR"), "/crates/rustudio-engine/build/source_claims.rs"));

/// The plugin API domain's claimer: it lives in studio (`src/plugin_host`),
/// above the engine, so its claims are generated here and handed to the
/// engine at registration (studio_hooks::install).
const PLUGIN_CLAIMER: (&str, &[&str]) = ("plugin", &["plugin_host/api"]);

/// Writes plugin_claims.rs: the plugin API domain's claim tables, the same
/// generation as member_claims.rs for one claimer. The domain lives in studio
/// (src/plugin_host, above the engine), so the engine's own member_claims.rs
/// cannot include it; src/plugin_host/api.rs includes this file and passes
/// the tables in its Domain at registration.
fn plugin_claims() {
    let mut code = String::new();
    for (table, root) in [
        ("CLAIMS", "prop_get"),
        ("CALL_CLAIMS", "call"),
        ("NEWINDEX_CLAIMS", "newindex"),
    ] {
        let (set, prs) = claim_set(PLUGIN_CLAIMER.1, root);
        code += &format!("/// src/plugin_host/api*.rs: the plugin domain's {table} (build.rs).\npub static {table}: &[&str] = &[\n");
        for w in &set {
            code += &format!("{w:?},");
        }
        code += "];\n";
        code += &format!(
            "/// The plugin domain's (key, class) literal pairs for {table}, sorted\n\
             /// by key (build.rs).\npub static {table}_PAIRS: &[(&str, &str)] = &[\n"
        );
        code += &pair_row(&prs);
        code += "];\n";
    }
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("plugin_claims.rs");
    std::fs::write(out, code).unwrap();
    println!("cargo:rerun-if-changed=src/plugin_host");
}

/// The first capitalised identifier-like string literal in `window`.
fn first_name(window: &str) -> Option<String> {
    let window = &window[..window.find(';').unwrap_or(window.len())];
    let mut rest = window;
    while let Some(q) = rest.find('"') {
        let after = &rest[q + 1..];
        let qe = after.find('"')?;
        let name = &after[..qe];
        if name.chars().next().is_some_and(|c| c.is_ascii_uppercase())
            && name.chars().all(|c| c.is_ascii_alphanumeric())
        {
            return Some(name.to_string());
        }
        rest = &after[qe + 1..];
    }
    None
}

fn collect(text: &str, needle: &str, span: usize, out: &mut BTreeSet<String>) {
    // A needle ending in a quote starts the literal itself: keep the quote.
    let back = usize::from(needle.ends_with('"'));
    let span = if span == 0 { 40 } else { span };
    let mut i = 0;
    while let Some(at) = text[i..].find(needle) {
        let start = i + at + needle.len() - back;
        let mut end = (start + span).min(text.len());
        while !text.is_char_boundary(end) {
            end -= 1;
        }
        if let Some(n) = first_name(&text[start..end]) {
            out.insert(n);
        }
        i = start;
    }
}

/// The text without `fn event_exists … }` bodies.
fn strip_event_lists(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(at) = rest.find("fn event_exists") {
        out.push_str(&rest[..at]);
        let after = &rest[at..];
        match after.find("\n}\n") {
            Some(end) => rest = &after[end + 3..],
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

/// Every capitalised identifier-like string literal.
fn literals(text: &str, out: &mut BTreeSet<String>) {
    for (i, part) in text.split('"').enumerate() {
        if i % 2 == 1
            && part.len() > 2
            && part.chars().next().is_some_and(|c| c.is_ascii_uppercase())
            && part.chars().all(|c| c.is_ascii_alphanumeric())
        {
            out.insert(part.to_string());
        }
    }
}

fn scan(dir: &Path, reads: &mut BTreeSet<String>, fires: &mut BTreeSet<String>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            scan(&p, reads, fires);
            continue;
        }
        let ext = p.extension().and_then(|x| x.to_str()).unwrap_or("");
        if ext != "rs" && ext != "luau" {
            continue;
        }
        // The generated stub table names every member without doing
        // anything with it: it must not count as the engine using them.
        if p.file_name().is_some_and(|n| n == "api_stubs.rs") {
            continue;
        }
        let Ok(text) = std::fs::read_to_string(&p) else { continue };
        if ext == "rs" {
            collect(&text, "prop(", 80, reads);
            // Any property it names for the stored value (reads or writes it:
            // `get(&ustr("X"))`, `insert(ustr("X"), …)`, `mark_prop(r, ustr("X"))`).
            collect(&text, "ustr(", 40, reads);
        }
        // Events: fire sites often take a name picked elsewhere (a match arm,
        // an if, a Luau signal object), so any string literal naming it in the
        // engine counts, outside the `event_exists` declaration lists (which
        // only say an event can be connected).
        literals(&strip_event_lists(&text), fires);
    }
}

fn list(name: &str, doc: &str, set: &BTreeSet<String>) -> String {
    let body: Vec<String> = set.iter().map(|n| format!("    {n:?},")).collect();
    format!("/// {doc} (generated by build.rs).\npub const {name}: &[&str] = &[\n{}\n];\n", body.join("\n"))
}

/// The trees the old single `src/` became. `rustudio-net` and
/// `rustudio-account` were separate crates before the split and their sources
/// never counted here; adding them would change the generated tables. The
/// engine's tree supplies the runtime code scanned for engine_reads.rs.
const TREES: &[&str] = &[
    "src",
    "crates/rustudio-engine/src",
    "crates/rustudio-player/src",
    "crates/rustudio-core/src",
    "crates/rustudio-physics/src",
    "crates/rustudio-render/src",
];

/// Writes engine_reads.rs: the property names the engine reads and the event
/// names it mentions, scanned from TREES (the gap telemetry in
/// rustudio-core takes them through `telemetry::install_engine_tables`).
fn engine_tables() {
    let (mut reads, mut fires) = (BTreeSet::new(), BTreeSet::new());
    for tree in TREES {
        println!("cargo:rerun-if-changed={tree}");
        scan(Path::new(tree), &mut reads, &mut fires);
    }
    let code = list("ENGINE_READS", "Property names the engine reads", &reads)
        + &list("ENGINE_FIRES", "Event names the engine fires", &fires);
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("engine_reads.rs");
    std::fs::write(out, code).unwrap();
}

/// RUSTUDIO_GIT_SHA: the commit being built (profiler captures carry it so
/// a capture says which build made it). Rebuilt when HEAD moves, not on
/// every edit; no git (a source archive): unset.
fn git_sha() {
    let git = |args: &[&str]| {
        std::process::Command::new("git")
            .args(args)
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
    };
    if let Some(sha) = git(&["rev-parse", "--short=10", "HEAD"]) {
        println!("cargo:rustc-env=RUSTUDIO_GIT_SHA={sha}");
    }
    // (a worktree's HEAD and its branch ref live in the git dirs git names)
    if let Some(dir) = git(&["rev-parse", "--absolute-git-dir"]) {
        println!("cargo:rerun-if-changed={dir}/HEAD");
    }
    if let (Some(common), Some(r)) = (git(&["rev-parse", "--git-common-dir"]), git(&["symbolic-ref", "-q", "HEAD"])) {
        let common = std::path::Path::new(&common);
        let common = if common.is_absolute() { common.to_path_buf() } else { std::env::current_dir().unwrap_or_default().join(common) };
        println!("cargo:rerun-if-changed={}", common.join(r).display());
    }
}

fn main() {
    println!("cargo:rerun-if-changed=assets/icons/rustudio.ico");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        winresource::WindowsResource::new()
            .set_icon("assets/icons/rustudio.ico")
            .compile()
            .expect("compile Windows application icon");
    }

    plugin_claims();
    engine_tables();
    git_sha();
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=crates/rustudio-engine/build/source_claims.rs");
}
